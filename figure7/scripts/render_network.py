"""Draw the 16 selected associations in Bailey's boxed radial Figure 7F style.

The input models are generated by analyze_network.R for 18 fixed candidate
variables. The two nonsignificant candidates remain in the numerical results;
only nominal p < 0.05 associations are drawn. Node order, red/blue coefficient
sign encoding, and the continuous edge-width scale preserve the selected panel.

Usage: python render_network.py OUTPUT [7F|all]
The output is one vector PDF and a CSV of its plotted edges. Statistical model
fitting is performed separately; this script uses their full-precision results.
"""

import csv
import math
from matplotlib.patches import Polygon, Rectangle
import network_plot_helpers as drawing

with (drawing.MODULE / "data/network_candidates.csv").open(newline="") as handle:
    CANDIDATES = [row["original_metadata_column"] for row in csv.DictReader(handle)]
ALL_DATA = {row["Variable"]: row for row in drawing.ALL}
drawing.DATA = {
    variable: ALL_DATA[variable]
    for variable in CANDIDATES
    if float(ALL_DATA[variable]["P_value"]) < .05
}
LABELS = {
    "mes_score": "Mesenchymal\nScore", "tcell_score": "T cell score",
    "cell_adhesion": "Cell-cell adhesion",
    "go_resp_electron_transport": "Respiratory electron\ntransport chain",
    "HPV_integration": "HPV integration", "p_emt_zt": "p-EMT",
    "kegg_ox_phos_score": "Oxidative\nphosphorylation", "Malignant": "Malignant\nCells",
    "kerat_score": "Keratinization\nScore", "emt_score": "EMT", "T cells CD4": "CD4 T cells",
    "Macrophage": "Macrophages", "Fibroblast": "Fibroblasts", "T cells CD8": "CD8 T cells",
    "Dendritic": "Dendritic Cells", "bcell_score": "B cell score",
}
drawing.LABELS = LABELS
drawing.EVIDENCE = {variable: -math.log10(float(row["P_value"])) for variable, row in drawing.DATA.items()}
drawing.LO, drawing.HI = min(drawing.EVIDENCE.values()), max(drawing.EVIDENCE.values())
WIDTH, HEIGHT = 180, 84
HUB = (70.8, 39.25)

# Fixed display coordinates retain the clockwise order and spacing of the
# selected Bailey-style panel. Positions convey layout, not effect magnitude.
NODE_COORDINATES = {
    "mes_score": (335, 530), "tcell_score": (610, 535), "cell_adhesion": (870, 490),
    "go_resp_electron_transport": (1010, 405), "HPV_integration": (1010, 310),
    "p_emt_zt": (1010, 215), "kegg_ox_phos_score": (940, 135), "Malignant": (845, 64),
    "kerat_score": (640, 58), "emt_score": (485, 56), "T cells CD4": (330, 67),
    "Macrophage": (205, 135), "Fibroblast": (160, 215), "T cells CD8": (145, 290),
    "Dendritic": (150, 370), "bcell_score": (185, 450),
}
POSITIONS = {variable: (x * WIDTH / 1500, y * HEIGHT / 610) for variable, (x, y) in NODE_COORDINATES.items()}
if len(CANDIDATES) != 18 or set(POSITIONS) != set(drawing.DATA):
    raise ValueError("The fitted associations do not match the selected 16-node panel")


def main():
    """Render straight spokes, boxed nodes, and the direction/p-value legends."""
    fig, ax = drawing.canvas(HEIGHT)
    edges = []
    for variable, (x, y) in POSITIONS.items():
        ax.plot(
            [HUB[0], x], [HUB[1], y], color=drawing.color(variable),
            lw=drawing.width(variable), solid_capstyle="butt", zorder=1,
        )
        edges.append(drawing.edge_row(variable, x, y))
    for variable, (x, y) in POSITIONS.items():
        drawing.text(ax, x, y, LABELS[variable], 9.8, ha="center", bbox={
            "boxstyle": "square,pad=0.19", "facecolor": "white",
            "edgecolor": "black", "linewidth": .75,
        })
    drawing.text(ax, *HUB, drawing.HUB, 10.2, ha="center", zorder=6, bbox={
        "boxstyle": "round,pad=0.42,rounding_size=0.55", "facecolor": "white",
        "edgecolor": "black", "linewidth": .9,
    })
    drawing.text(
        ax, 162, 60, "Association with\n" + r"$\mathrm{E6FL}\!:\!\mathrm{E6}_{\mathrm{ALL}}$" + " score:",
        8.8, ha="center", linespacing=1.15,
    )
    for y, color, label in [(49, drawing.BLUE, "Negative"), (43, drawing.RED, "Positive")]:
        ax.add_patch(Rectangle((150.5, y - 1.35), 2.7, 2.7, facecolor=color, edgecolor="none"))
        drawing.text(ax, 155.2, y, label, 9)
    drawing.text(ax, 162, 30, "Width of edge:\np value", 9, ha="center", linespacing=1.08)

    # The tapered legend uses precisely the same width mapping as the edges.
    p_min = min(float(row["P_value"]) for row in drawing.DATA.values())
    p_max = max(float(row["P_value"]) for row in drawing.DATA.values())
    left, right, center_y = 150, 174, 21
    thick = drawing.pwidth(p_min) * 25.4 / 72 / 2
    thin = drawing.pwidth(p_max) * 25.4 / 72 / 2
    ax.add_patch(Polygon(
        [(left, center_y - thick), (right, center_y - thin),
         (right, center_y + thin), (left, center_y + thick)],
        facecolor="#222222", edgecolor="none", zorder=5,
    ))
    exponent = math.floor(math.log10(p_min))
    minimum_label = rf"${p_min / (10 ** exponent):.2f}\!\times\!10^{{{exponent}}}$"
    drawing.text(ax, left, 15.5, minimum_label, 8.3, ha="center")
    drawing.text(ax, right, 15.5, f"{p_max:.4f}", 8.3, ha="center")
    drawing.save(fig, edges)
    print("Rendered Figure 7F with 16 associations.")


if __name__ == "__main__":
    main()
